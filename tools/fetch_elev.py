#!/usr/bin/env python3
"""Real ground elevation for the 万锦三国志 strategy map (v0.8, D-74).

Samples a grid over maps/markham.json (every STEP game metres) from the Open-Meteo elevation API
(Copernicus DEM GLO-90, free, no key) and writes js/sg_elev.js: a small module the strategy screen
uses for hill shading and the rules use for high ground (cities and passes on higher ground are
harder to attack). Needs network; the output is committed, so the game never calls the API.

    python3 tools/fetch_elev.py
"""
import json, math, os, time, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAP = os.path.join(ROOT, 'maps', 'markham.json')
OUT = os.path.join(ROOT, 'js', 'sg_elev.js')
STEP = 100.0  # game metres between samples (= 250 real metres)

m = json.load(open(MAP, encoding='utf-8'))
HW, HH = m['half']
A = math.radians(m['rot'])
o = m['origin']
LAT0, LON0 = o['lat0'], o['lon0']


def latlon(gx, gz):
    """game metres -> (lat, lon); the inverse of build_map.py's proj / rot / g"""
    x, z = gx / m['scale'] + o['cx'], gz / m['scale'] + o['cz']
    X, Z = x * math.cos(A) - z * math.sin(A), x * math.sin(A) + z * math.cos(A)
    return LAT0 - Z / 110574.0, LON0 + X / (math.cos(math.radians(LAT0)) * 111320.0)


nx, nz = int(2 * HW // STEP) + 2, int(2 * HH // STEP) + 2
pts = [latlon(-HW + i * STEP, -HH + j * STEP) for j in range(nz) for i in range(nx)]
elev = []
for k in range(0, len(pts), 100):
    chunk = pts[k:k + 100]
    url = 'https://api.open-meteo.com/v1/elevation?latitude=%s&longitude=%s' % (
        ','.join('%.5f' % p[0] for p in chunk), ','.join('%.5f' % p[1] for p in chunk))
    for attempt in range(5):
        try:
            with urllib.request.urlopen(url, timeout=30) as r:
                elev += [round(v) for v in json.load(r)['elevation']]
            break
        except Exception as e:  # rate limit / network: back off and retry
            print('retry', attempt, e)
            time.sleep(2 ** attempt)
    else:
        raise SystemExit('elevation API failed')
    time.sleep(0.3)

lo, hi = min(elev), max(elev)
print('grid %d x %d, elevation %d..%d m' % (nx, nz, lo, hi))
with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/fetch_elev.py (D-74): real ground elevation in metres above sea level,\n')
    f.write('// Copernicus DEM GLO-90 via the Open-Meteo elevation API. Row-major, row 0 = north edge.\n')
    f.write('export const ELEV = { step: %d, x0: %.1f, z0: %.1f, nx: %d, nz: %d, lo: %d, hi: %d,\n' % (STEP, -HW, -HH, nx, nz, lo, hi))
    f.write('  h: [\n')
    for j in range(nz):
        f.write('    ' + ','.join(str(v) for v in elev[j * nx:(j + 1) * nx]) + ',\n')
    f.write('  ] };\n')
print('wrote', OUT)
